"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import {
  ArrowRight,
  Check,
  Download,
  FileSpreadsheet,
  LoaderCircle,
} from "lucide-react";
import { useRouter } from "next/navigation";
import { useState } from "react";

import { PageIntro } from "@/components/layout/page-intro";
import { WorkspaceGate } from "@/components/layout/workspace-gate";
import { ApiErrorState, EmptyState } from "@/components/states/api-state";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { CardSkeleton } from "@/components/ui/skeleton";
import { api } from "@/lib/api/client";
import { cn, formatCount, titleCase } from "@/lib/utils";

const tones = [
  "bg-[var(--green-soft)]",
  "bg-[var(--coral-soft)]",
  "bg-[var(--yellow-soft)]",
  "bg-[var(--violet-soft)]",
];

export default function ScenariosPage() {
  return (
    <WorkspaceGate>
      <ScenarioSelector />
    </WorkspaceGate>
  );
}

function ScenarioSelector() {
  const router = useRouter();
  const queryClient = useQueryClient();
  const [selectedSlug, setSelectedSlug] = useState<string | null>(null);
  const scenarios = useQuery({
    queryKey: ["scenarios"],
    queryFn: api.scenarios,
  });
  const detail = useQuery({
    queryKey: ["scenario", selectedSlug],
    queryFn: () => api.scenario(selectedSlug ?? ""),
    enabled: Boolean(selectedSlug),
  });
  const load = useMutation({
    mutationFn: (slug: string) => api.loadScenario(slug),
    async onSuccess() {
      await Promise.all([
        queryClient.invalidateQueries({ queryKey: ["imports"] }),
        queryClient.invalidateQueries({ queryKey: ["runs"] }),
      ]);
      router.push("/imports?loaded=1");
    },
  });

  const items = scenarios.data?.items ?? [];
  const selected =
    detail.data ?? items.find((item) => item.slug === selectedSlug) ?? null;

  return (
    <>
      <PageIntro
        eyebrow="Step 1 · Choose a controlled input"
        title="Select a scenario"
        description="Each scenario is generated by Java from a fixed seed and includes three source files plus a ground-truth manifest. Load one into this isolated workspace."
      />

      {scenarios.isPending ? (
        <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-4">
          {Array.from({ length: 4 }).map((_, index) => (
            <CardSkeleton key={index} />
          ))}
        </div>
      ) : scenarios.error ? (
        <ApiErrorState
          error={scenarios.error}
          onRetry={() => void scenarios.refetch()}
        />
      ) : items.length === 0 ? (
        <EmptyState
          title="No scenarios are available"
          description="The service returned no prepared datasets. Check the dataset generator or retry after the backend finishes starting."
          action={
            <Button onClick={() => void scenarios.refetch()}>Retry</Button>
          }
        />
      ) : (
        <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-4">
          {items.map((scenario, index) => (
            <button
              key={scenario.slug}
              type="button"
              onClick={() => setSelectedSlug(scenario.slug)}
              aria-pressed={selectedSlug === scenario.slug}
              className={cn(
                "group min-h-72 rounded-[var(--radius-card)] border p-5 text-left shadow-[var(--shadow-card)] transition-transform focus-visible:ring-3 focus-visible:ring-[var(--focus)] focus-visible:outline-none motion-safe:hover:-translate-y-1",
                tones[index % tones.length],
                selectedSlug === scenario.slug
                  ? "border-[var(--ink)] ring-2 ring-[var(--ink)]"
                  : "border-[var(--border)]",
              )}
            >
              <div className="flex items-start justify-between gap-4">
                <span className="utility-label text-[var(--muted)]">
                  {scenario.slug.replaceAll("-", " ")}
                </span>
                <span
                  className={cn(
                    "grid size-9 place-items-center rounded-full border",
                    selectedSlug === scenario.slug
                      ? "border-[var(--ink)] bg-[var(--ink)] text-white"
                      : "border-[var(--border-strong)] bg-white",
                  )}
                >
                  {selectedSlug === scenario.slug ? (
                    <Check size={18} aria-hidden="true" />
                  ) : (
                    <ArrowRight size={18} aria-hidden="true" />
                  )}
                </span>
              </div>
              <h2 className="mt-12 font-display text-4xl leading-[0.9] font-bold uppercase">
                {scenario.name}
              </h2>
              <p className="mt-3 line-clamp-3 text-sm leading-6 text-[var(--muted-strong)]">
                {scenario.purpose}
              </p>
              <dl className="mt-6 grid grid-cols-2 gap-2 border-t border-black/10 pt-4">
                <div>
                  <dt className="utility-label text-[var(--muted)]">
                    Payments
                  </dt>
                  <dd className="font-display text-2xl font-bold">
                    {formatCount(scenario.canonicalPaymentCount)}
                  </dd>
                </div>
                <div>
                  <dt className="utility-label text-[var(--muted)]">
                    Exceptions
                  </dt>
                  <dd className="font-display text-2xl font-bold">
                    {formatCount(scenario.expectedExceptionCount)}
                  </dd>
                </div>
              </dl>
            </button>
          ))}
        </div>
      )}

      {selected ? (
        <Card className="mt-3 overflow-hidden">
          <div className="grid lg:grid-cols-[.72fr_1.28fr]">
            <div className="border-b border-[var(--border)] bg-[var(--ink)] p-6 text-white sm:p-8 lg:border-r lg:border-b-0">
              <p className="utility-label text-white/50">Scenario preview</p>
              <h2 className="mt-3 font-display text-5xl leading-[0.85] font-bold uppercase">
                {selected.name}
              </h2>
              <p className="mt-5 text-sm leading-7 text-white/70">
                {selected.description ?? selected.purpose}
              </p>
              <div className="mt-8 rounded-2xl border border-white/10 bg-white/5 p-4 text-xs leading-6 text-white/70">
                {selected.controlledFailureAfterChunks ? (
                  <>
                    This recovery exercise intentionally interrupts its first
                    run after {selected.controlledFailureAfterChunks} chunks.
                    Restart the failed run to continue from its last checkpoint.
                  </>
                ) : (
                  <>
                    The expected exception count is validation evidence, not a
                    frontend rule. The Spring service calculates every actual
                    outcome.
                  </>
                )}
              </div>
            </div>
            <div className="p-5 sm:p-8">
              <div className="flex items-center justify-between gap-4">
                <div>
                  <p className="utility-label text-[var(--muted)]">
                    Input files
                  </p>
                  <h3 className="mt-1 font-display text-3xl font-bold uppercase">
                    Inspect before loading
                  </h3>
                </div>
                {detail.isFetching ? (
                  <LoaderCircle
                    className="animate-spin"
                    size={22}
                    aria-label="Loading scenario details"
                  />
                ) : null}
              </div>
              <div className="mt-5 divide-y divide-[var(--border)] rounded-2xl border border-[var(--border)] bg-[var(--surface-muted)]">
                {(selected.availableFiles ?? []).map((file) => (
                  <div
                    key={file.fileName}
                    className="flex flex-col gap-3 p-4 sm:flex-row sm:items-center"
                  >
                    <span className="grid size-10 shrink-0 place-items-center rounded-full bg-white">
                      <FileSpreadsheet size={21} aria-hidden="true" />
                    </span>
                    <div className="min-w-0 flex-1">
                      <p className="truncate text-sm font-bold">
                        {file.fileName}
                      </p>
                      <p className="mt-1 font-mono text-[0.65rem] text-[var(--muted)]">
                        {file.sourceType
                          ? titleCase(file.sourceType)
                          : "Supporting artifact"}{" "}
                        · {formatCount(file.rowCount)} rows
                        {file.checksum
                          ? ` · SHA-256 ${file.checksum.slice(0, 12)}…`
                          : null}
                      </p>
                    </div>
                    <Button
                      variant="secondary"
                      size="sm"
                      onClick={() =>
                        void api.downloadScenarioFile(
                          selected.slug,
                          file.fileName,
                        )
                      }
                    >
                      <Download
                        size={16}

                        aria-hidden="true"
                      />
                      Download
                    </Button>
                  </div>
                ))}
                {(selected.availableFiles ?? []).length === 0 &&
                !detail.isFetching ? (
                  <p className="p-4 text-sm text-[var(--muted)]">
                    File details are unavailable for this scenario.
                  </p>
                ) : null}
              </div>
              <div className="mt-6 flex flex-col justify-between gap-4 rounded-2xl bg-[var(--coral-soft)] p-4 sm:flex-row sm:items-center">
                <p className="max-w-lg text-xs leading-5 text-[var(--muted-strong)]">
                  Use synthetic demonstration data only. Do not upload real
                  payment, customer, card or bank information.
                </p>
                <Button
                  variant="primary"
                  disabled={load.isPending}
                  onClick={() => load.mutate(selected.slug)}
                >
                  {load.isPending ? (
                    <LoaderCircle
                      className="animate-spin"
                      size={18}
                      aria-hidden="true"
                    />
                  ) : (
                    <ArrowRight size={18} aria-hidden="true" />
                  )}
                  Load sample data
                </Button>
              </div>
              {load.error ? (
                <div className="mt-4">
                  <ApiErrorState
                    error={load.error}
                    onRetry={() => load.mutate(selected.slug)}
                  />
                </div>
              ) : null}
            </div>
          </div>
        </Card>
      ) : null}
    </>
  );
}
